/**
 * 拼装发给模型的 system 提示词：人设 + 本次服务的旅行上下文。
 * 人设放在服务端而不是小程序里：改文案不用重新提审，客户端也无法篡改。
 *
 * @param {{travelContext?: string, override?: string}} [options]
 *   travelContext 为本次国家资料的文本快照；override 为 AI_SYSTEM_PROMPT 的整体覆盖。
 * @returns {string} 完整的 system 消息内容。
 */
function buildSystemPrompt(options = {}) {
  const override = String(options.override || '').trim();
  if (override) {
    return override;
  }
  const travelContext = String(options.travelContext || '').trim();
  return [
    PERSONA_BODY,
    '',
    '【当前旅行上下文】',
    travelContext || NO_CONTEXT_NOTE
  ].join('\n');
}

module.exports = {
  PERSONA_TITLE,
  PERSONA_BODY,
  NO_CONTEXT_NOTE,
  buildSystemPrompt
};
